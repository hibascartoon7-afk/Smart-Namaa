// Growth-stage lengths of a crop: read the CSV template, check every row, and write the SQL that stores them.
// Pure functions (tested). The numbers always come from the person who fills the CSV (FAO-56 Table 11 or her own
// measurements); this module contains no stage length.

export const COLUMNS = ['crop_name', 'initial_days', 'development_days', 'mid_days', 'late_days', 'source_id', 'value_basis'];
const DAY_COLUMNS = ['initial_days', 'development_days', 'mid_days', 'late_days'];
/** a typo guard (an extra zero), not a scientific limit */
export const MAX_STAGE_DAYS = 1000;

/** RFC-4180 style CSV reader: quotes, doubled quotes, commas and line breaks inside quotes, BOM, CRLF */
export function parseCsv(text) {
  const src = text.replace(/^\uFEFF/, '');
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') { cell += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      rows.push(row); row = [];
    } else cell += ch;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim() !== ''));
}

/**
 * Rows of the CSV -> { rows (valid, filled), skipped (crops with all four day cells empty), errors }.
 * Rules (the same ones the engine applies in kc-curve.ts): initial >= 0, development > 0, mid >= 0, late > 0, whole days.
 */
export function readStages(csvText) {
  const table = parseCsv(csvText);
  const errors = [];
  if (table.length === 0) return { rows: [], skipped: [], errors: ['the file is empty'] };
  const header = table[0].map((h) => h.trim());
  const missingColumns = COLUMNS.filter((c) => !header.includes(c));
  if (missingColumns.length) return { rows: [], skipped: [], errors: [`missing column(s): ${missingColumns.join(', ')}`] };
  const at = Object.fromEntries(COLUMNS.map((c) => [c, header.indexOf(c)]));

  const rows = [];
  const skipped = [];
  const seen = new Set();
  table.slice(1).forEach((cells, i) => {
    const line = i + 2;
    const get = (c) => (cells[at[c]] ?? '').trim();
    const name = get('crop_name');
    if (!name) { errors.push(`line ${line}: crop_name is empty`); return; }
    const days = Object.fromEntries(DAY_COLUMNS.map((c) => [c, get(c)]));
    if (DAY_COLUMNS.every((c) => days[c] === '')) { skipped.push(name); return; }

    const problems = [];
    if (seen.has(name.toLowerCase())) problems.push('the crop appears twice in the file');
    seen.add(name.toLowerCase());
    const n = {};
    for (const c of DAY_COLUMNS) {
      if (days[c] === '') problems.push(`${c} is empty (fill all four stages or leave all four empty)`);
      else if (!/^\d+$/.test(days[c])) problems.push(`${c} must be a whole number of days, got "${days[c]}"`);
      else if (Number(days[c]) > MAX_STAGE_DAYS) problems.push(`${c} is above ${MAX_STAGE_DAYS} days: a typo?`);
      else n[c] = Number(days[c]);
    }
    if (n.development_days !== undefined && n.development_days <= 0) problems.push('development_days must be more than 0');
    if (n.late_days !== undefined && n.late_days <= 0) problems.push('late_days must be more than 0');
    // numbers need a place they come from: a source id, or (for the owner's own observation) a written basis
    const sourceId = get('source_id');
    const basis = get('value_basis');
    if (sourceId !== '' && !/^[A-Za-z0-9_]+$/.test(sourceId)) problems.push('source_id must be an id from the sources table (letters / digits / underscore)');
    if (sourceId === '' && basis === '') problems.push('say where the numbers come from: a source_id, or value_basis (for example "observed on my field, planting 2026-03-01")');
    if (problems.length) { errors.push(`line ${line} (${name}): ${problems.join('; ')}`); return; }
    rows.push({ crop_name: name, ...n, source_id: sourceId === '' ? null : sourceId, value_basis: basis === '' ? null : basis });
  });
  return { rows, skipped, errors };
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

/** SQL for the SQL editor of Supabase. Stops (and stores nothing) when a crop name or a source id does not exist. */
export function buildSql(rows, fileLabel = 'crop_growth_stages.csv') {
  if (rows.length === 0) throw new Error('nothing to store: no row has its four stage lengths filled');
  const values = rows
    .map((r) => `  (${q(r.crop_name)}, ${r.initial_days}, ${r.development_days}, ${r.mid_days}, ${r.late_days}, ${r.source_id ? q(r.source_id) : 'null'}, ${r.value_basis ? q(r.value_basis) : 'null'})`)
    .join(',\n');
  return `-- Generated by scripts/import-growth-stages.mjs from ${fileLabel.replace(/[\r\n]/g, ' ')}. ${rows.length} crop(s).
-- Run it in the Supabase SQL editor. It stops with an error (and stores nothing) if a crop name or a source id is unknown.
-- Running it twice is safe: a row that is already stored with the same numbers is not added again.
-- The engine reads the NEWEST row of a crop, so a row stored now wins over an older one (older rows are kept).
begin;

create temporary table _new_stages (
  crop_name text, initial_days int, development_days int, mid_days int, late_days int, source_id text, value_basis text
) on commit drop;

insert into _new_stages values
${values};

do $$
declare bad text;
begin
  select string_agg(n.crop_name, ', ') into bad
    from _new_stages n where not exists (select 1 from public.crops c where c.crop_name = n.crop_name);
  if bad is not null then raise exception 'Unknown crop name(s) (must match public.crops.crop_name exactly): %', bad; end if;

  select string_agg(distinct n.source_id, ', ') into bad
    from _new_stages n where n.source_id is not null and not exists (select 1 from public.sources s where s.id = n.source_id);
  if bad is not null then raise exception 'Unknown source id(s) (add them to public.sources first): %', bad; end if;
end $$;

insert into public.crop_growth_stages (crop_id, initial_days, development_days, mid_days, late_days, source_id, value_basis)
select c.id, n.initial_days, n.development_days, n.mid_days, n.late_days, n.source_id, n.value_basis
  from _new_stages n
  join public.crops c on c.crop_name = n.crop_name
 where not exists (
   select 1 from public.crop_growth_stages g
    where g.crop_id = c.id and g.initial_days = n.initial_days and g.development_days = n.development_days
      and g.mid_days = n.mid_days and g.late_days = n.late_days
 );

commit;

-- Check: every crop you filled should now say has_stage_lengths = true
select crop_name, has_kc, has_water_params, has_stage_lengths from public.crop_readiness order by crop_name;
`;
}
