// One engine, three places. src/engine is the ONLY place to edit. This script copies it to:
//   - supabase/functions/_shared/engine   (Deno needs ".ts" at the end of every relative import: added here)
//   - namaa-agritech/src/lib/engine       (the few pure modules the web app uses)
// Run:  npm run sync-engine      Check only (used by the tests):  npm run check-sync
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src', 'engine');
const WEB_FILES = ['et0.ts', 'idw.ts', 'middle-zone.ts', 'stats.ts', 'time.ts', 'weather-summary.ts'];

const addTsExtension = (code) => code.replace(/from '(\.[^']*)'/g, (m, p) => (p.endsWith('.ts') ? m : `from '${p}.ts'`));

export const TARGETS = [
  { dir: join(ROOT, 'supabase', 'functions', '_shared', 'engine'), files: null, transform: addTsExtension },
  { dir: join(ROOT, 'namaa-agritech', 'src', 'lib', 'engine'), files: WEB_FILES, transform: (c) => c },
];

const banner = (f) => `// GENERATED by scripts/sync-engine.mjs from src/engine/${f}. Do not edit here: edit the original and run "npm run sync-engine".\n`;

export function expectedFiles() {
  const out = [];
  for (const t of TARGETS) {
    const names = (t.files ?? readdirSync(SRC).filter((f) => f.endsWith('.ts'))).sort();
    for (const f of names) out.push({ path: join(t.dir, f), content: banner(f) + t.transform(readFileSync(join(SRC, f), 'utf-8')) });
  }
  return out;
}

export function run(check) {
  const bad = [];
  for (const { path, content } of expectedFiles()) {
    const current = existsSync(path) ? readFileSync(path, 'utf-8') : null;
    if (current === content) continue;
    if (check) bad.push(path.replace(ROOT, ''));
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  return bad;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const bad = run(check);
  if (check && bad.length) {
    console.error('Out of sync with src/engine:\n' + bad.join('\n') + '\nRun: npm run sync-engine');
    process.exit(1);
  }
  console.log(check ? 'engine copies are in sync' : 'engine copied');
}
